import assert from 'node:assert/strict';
import { mkdir } from 'node:fs/promises';
import { createServer } from 'vite';

const { chromium } = await import(process.env.PLAYWRIGHT_MODULE ?? 'playwright');
const server = await createServer({ server: { host: '127.0.0.1', port: 0 } });
let browser;
try {
  await server.listen();
  browser = await chromium.launch({ headless: true });
  const context = await browser.newContext({ viewport: { width: 1440, height: 1000 } });
  await context.route('https://**/*', route => route.fulfill({ body: 'Destination' }));
  const page = await context.newPage();
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  const origin = `http://127.0.0.1:${server.httpServer.address().port}`;
  await page.goto(origin);
  await page.evaluate(() => {
    localStorage.setItem('jipage_bookmarks_v1', '[]');
    localStorage.setItem('jipage_folders_v1', '[]');
  });
  await page.reload();
  await page.getByTitle('添加新网址到桌面 (⌘N)').first().click();
  const dialog = page.getByRole('dialog');
  await dialog.getByLabel('网址 URL', { exact: true }).fill('example.org/photos');
  await dialog.getByLabel('网站名称', { exact: true }).fill('Unsplash');
  await dialog.getByLabel('搜索关键词（可选）').fill('图片，壁纸,图片');
  await dialog.getByLabel('搜索关键词（可选）').press('Enter');
  assert.equal(await dialog.isVisible(), true, 'Enter confirms a keyword without submitting');
  assert.equal(await dialog.getByRole('button', { name: '移除关键词 图片', exact: true }).count(), 1);
  await dialog.getByRole('button', { name: '添加收藏', exact: true }).click();
  await dialog.waitFor({ state: 'hidden' });
  assert.deepEqual(await page.evaluate(() => JSON.parse(localStorage.getItem('jipage_library_v2')).bookmarks[0].keywords), ['图片', '壁纸']);
  await page.getByRole('banner').getByRole('button', { name: '管理中心', exact: true }).click();
  await page.getByPlaceholder('按名称、网址或关键词搜索...').fill('壁纸');
  await page.getByRole('main').getByText('Unsplash', { exact: true }).waitFor();
  await page.getByTitle('编辑收藏').click();
  await dialog.getByLabel('网站名称').fill('Photo desk');
  await dialog.getByRole('button', { name: '移除关键词 图片', exact: true }).click();
  await dialog.getByRole('button', { name: '移除关键词 壁纸', exact: true }).click();
  await dialog.getByLabel('搜索关键词（可选）').fill('素材，摄影');
  // Failed edit must retain its draft and leave the saved bookmark untouched.
  await page.evaluate(() => {
    window.originalSetItem = Storage.prototype.setItem;
    Storage.prototype.setItem = () => { throw new DOMException('Full', 'QuotaExceededError'); };
  });
  await dialog.getByRole('button', { name: '保存更改' }).click();
  await dialog.getByRole('alert').filter({ hasText: '空间不足' }).waitFor();
  assert.equal(await dialog.getByLabel('网站名称').inputValue(), 'Photo desk');
  assert.equal(await page.evaluate(() => JSON.parse(localStorage.getItem('jipage_library_v2')).bookmarks[0].title), 'Unsplash');
  await page.evaluate(() => { Storage.prototype.setItem = window.originalSetItem; });
  await dialog.getByRole('button', { name: '保存更改' }).click();
  await dialog.waitFor({ state: 'hidden' });
  await page.getByPlaceholder('按名称、网址或关键词搜索...').fill('摄影');
  await page.getByRole('main').getByText('Photo desk', { exact: true }).waitFor();
  await page.getByTitle('点击返回首页桌面').click();
  await page.getByRole('button', { name: /^(打开搜索|Open search)$/ }).click();
  await page.getByPlaceholder('搜索或输入网址').fill('素材');
  await page.getByText('Photo desk', { exact: true }).first().waitFor();
  await page.keyboard.press('Escape');
  await page.getByTitle('启动台 · 所有应用与收藏 (桌面上滑亦可展开)').click();
  await page.getByRole('searchbox', { name: '搜索收藏', exact: true }).fill('素材');
  const result = page.getByRole('dialog', { name: '启动台', exact: true }).getByRole('button', { name: 'Photo desk', exact: true });
  await result.waitFor();
  const popupPromise = context.waitForEvent('page');
  await result.click();
  const popup = await popupPromise;
  await popup.waitForLoadState();
  assert.equal(popup.url(), 'https://example.org/photos');
  await popup.close();
  await page.reload();
  await page.getByTitle('启动台 · 所有应用与收藏 (桌面上滑亦可展开)').click();
  await page.getByRole('searchbox', { name: '搜索收藏', exact: true }).fill('素材');
  await page.getByRole('dialog', { name: '启动台', exact: true }).getByRole('button', { name: 'Photo desk', exact: true }).waitFor();
  await page.getByTitle('关闭启动台 (Esc 或点击空白处)').click();
  await page.getByTitle('添加新网址到桌面 (⌘N)').first().click();
  await dialog.getByLabel('网址 URL', { exact: true }).fill('example.org/another');
  await dialog.getByLabel('网站名称', { exact: true }).fill('Keep my input');
  await page.evaluate(() => {
    window.originalSetItem = Storage.prototype.setItem;
    Storage.prototype.setItem = () => { throw new DOMException('Full', 'QuotaExceededError'); };
  });
  await dialog.getByRole('button', { name: '添加收藏', exact: true }).click();
  await dialog.getByRole('alert').filter({ hasText: '空间不足' }).waitFor();
  assert.equal(await dialog.getByLabel('网站名称', { exact: true }).inputValue(), 'Keep my input');
  assert.equal(await page.evaluate(() => JSON.parse(localStorage.getItem('jipage_library_v2')).bookmarks.length), 1);
  await page.evaluate(() => { Storage.prototype.setItem = window.originalSetItem; });
  await dialog.getByRole('button', { name: '取消', exact: true }).click();
  await page.getByRole('banner').getByRole('button', { name: '管理中心', exact: true }).click();
  await page.getByTitle('编辑收藏').click();
  await mkdir('test-results/screenshots', { recursive: true });
  await page.screenshot({ path: 'test-results/screenshots/manual-bookmark-edit.png', fullPage: true });
  await page.setViewportSize({ width: 390, height: 844 });
  await page.screenshot({ path: 'test-results/screenshots/manual-bookmark-mobile.png', fullPage: true });
  assert.equal(await dialog.getByLabel('搜索关键词（可选）').isVisible(), true);
  assert.deepEqual(errors, []);
  console.log('PASS: manual add → edit title/keywords → keyword search → launchpad open → reload; failed add/edit retains draft and data; desktop/mobile screenshots');
} finally {
  await browser?.close();
  await server.close();
}
